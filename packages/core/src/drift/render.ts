/**
 * Drift report → markdown.
 *
 * The output is committed, so it may contain only derived structure: directory
 * labels, category ids, key *names*, counts, booleans, fingerprints. Never a
 * string value, never a file basename (an unrecognised filename can itself be
 * personal, and a caption definitely is). `privacy.test.ts` fails if any value
 * from the input reaches this text.
 */
import type { ChangedCategory, DriftReport } from "./drift.js";

function cell(a: number, b: number): string {
  return a === b ? `| ${a} | ${b} |` : `| ${a} | **${b}** |`;
}

function countRow(label: string, a: number, b: number): string {
  return `| ${label} ${cell(a, b)}`;
}

function list(items: readonly string[], empty: string): string {
  return items.length === 0 ? empty : items.map((item) => `\`${item}\``).join(", ");
}

function keys(keys: readonly string[]): string {
  return keys.length === 0 ? "—" : keys.map((key) => `\`${key}\``).join(", ");
}

function flags(satisfied: readonly boolean[]): string {
  if (satisfied.length === 0) return "no signature";
  return satisfied.map((flag) => (flag ? "ok" : "**stale**")).join(", ");
}

/** A shape change is about keys, signatures or the media base — not the row count. */
function isShapeChange(change: ChangedCategory): boolean {
  return (
    change.keysAdded.length > 0 ||
    change.keysRemoved.length > 0 ||
    change.signaturesStillSatisfied.a.join() !== change.signaturesStillSatisfied.b.join() ||
    change.mediaPathUsed.a !== change.mediaPathUsed.b
  );
}

function shapeRow(change: ChangedCategory): string {
  const cells = [
    `\`${change.id}\``,
    `${change.entryCount.a} → ${change.entryCount.b}`,
    keys(change.keysAdded),
    keys(change.keysRemoved),
    `${flags(change.signaturesStillSatisfied.a)} / ${flags(change.signaturesStillSatisfied.b)}`,
    `${change.mediaPathUsed.a} / ${change.mediaPathUsed.b}`,
  ];
  return `| ${cells.join(" | ")} |`;
}

/**
 * `date` is passed in rather than read from the clock so the same input renders
 * byte-identical output — the drift doc has to be reviewable as a diff.
 */
export function renderDrift(report: DriftReport, date: string, note?: string): string {
  const lines: string[] = [];
  const { a, b } = report.labels;

  lines.push(`# Drift — \`${a}/\` vs \`${b}/\` — ${date}`, "");
  lines.push(
    "Derived structure only: counts, category ids, key names, fingerprints. No personal content.",
    "",
    "_Generated by `pnpm drift` (`packages/core/src/drift/render.ts`). Do not hand-edit: re-run it._",
    "",
  );
  if (note !== undefined) {
    lines.push(note, "");
  }

  lines.push("## Fingerprints", "");
  lines.push(`| | \`${a}/\` | \`${b}/\` |`, "| --- | --- | --- |");
  lines.push(`| fingerprint | \`${report.fingerprints.a}\` | \`${report.fingerprints.b}\` |`);
  const sameFingerprint = report.fingerprints.a === report.fingerprints.b;
  lines.push(
    `| verdict | ${
      sameFingerprint ? "identical shape" : "different shape — non-blocking warning (ADR 0005)"
    } | |`,
    "",
  );

  lines.push("## Media", "");
  lines.push("| Measure | old | new |", "| --- | --- | --- |");
  lines.push(countRow("media-looking files", report.media.filesA, report.media.filesB));
  lines.push(countRow("bytes", report.media.bytesA, report.media.bytesB));
  lines.push(
    countRow("orphans (media no reference claims)", report.media.orphansA, report.media.orphansB),
    "",
  );

  lines.push("## Mojibake", "");
  lines.push("| Measure | old | new |", "| --- | --- | --- |");
  lines.push(countRow("strings repaired", report.mojibake.stringsA, report.mojibake.stringsB));
  lines.push(
    countRow("categories affected", report.mojibake.categoriesA, report.mojibake.categoriesB),
    "",
  );

  lines.push(
    `## Categories only in the older export, \`${a}/\` (${report.categoriesOnlyInA.length})`,
    "",
  );
  lines.push(
    "Absence is normal (ADR 0002): these rows are not deleted, they are simply not in the",
    "second export.",
    "",
    list(report.categoriesOnlyInA, "None."),
    "",
  );

  lines.push(
    `## Categories only in the newer export, \`${b}/\` (${report.categoriesOnlyInB.length})`,
    "",
  );
  lines.push(list(report.categoriesOnlyInB, "None."), "");

  const shapeChanges = report.changed.filter(isShapeChange);

  lines.push(`## Measured shape changes (${shapeChanges.length})`, "");
  if (shapeChanges.length === 0) {
    lines.push("None.", "");
  } else {
    lines.push(
      "`signatures` lists every signature on the registry row, in row order, evaluated against",
      "that export (ADR 0008). `stale` means the row's recorded shape is not what this export",
      "wrote — the name still resolves it, the shape no longer describes it.",
      "",
      "| Category | entries | keys added | keys removed | signatures (old / new) | media path (old / new) |",
      "| --- | --- | --- | --- | --- | --- |",
      ...shapeChanges.map(shapeRow),
      "",
    );
  }

  const countChanges = report.changed.filter((change) => !isShapeChange(change));
  if (countChanges.length > 0) {
    lines.push(`## Count changes only (${countChanges.length})`, "");
    lines.push("Same keys, same signatures — only the number of entries differs.", "");
    for (const change of countChanges) {
      lines.push(`- \`${change.id}\` — ${change.entryCount.a} → ${change.entryCount.b}`);
    }
    lines.push("");
  }

  const mediaRows = report.changed.filter(
    (change) =>
      change.media.refsA !== change.media.refsB || change.media.missingA !== change.media.missingB,
  );
  if (mediaRows.length > 0) {
    lines.push("## Media reference counts that differ", "");
    lines.push("| Category | references | missing |", "| --- | --- | --- |");
    for (const change of mediaRows) {
      lines.push(
        `| \`${change.id}\` | ${change.media.refsA} → ${change.media.refsB} | ${change.media.missingA} → ${change.media.missingB} |`,
      );
    }
    lines.push("");
  }

  lines.push(
    `## Unrecognised — old: ${report.unrecognised.a.length}, new: ${report.unrecognised.b.length}`,
    "",
  );
  if (report.unrecognised.a.length === 0 && report.unrecognised.b.length === 0) {
    lines.push("None in either export.", "");
  } else {
    lines.push(
      "Filenames are withheld: an unrecognised basename is not structural. The shapes are enough",
      "to recognise a file again with `pnpm drift --propose`.",
      "",
      "| export | # | kind | entries | keys |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const [label, shapes] of [
      [a, report.unrecognised.a],
      [b, report.unrecognised.b],
    ] as const) {
      shapes.forEach((shape, index) => {
        lines.push(
          `| ${label} | ${index + 1} | ${shape.kind} | ${shape.entryCount} | ${keys(shape.keys)} |`,
        );
      });
    }
    lines.push("");
  }

  return lines.join("\n");
}
